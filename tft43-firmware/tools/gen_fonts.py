#!/usr/bin/env python3
"""Generate src/fonts.c: anti-aliased (4 bits per pixel) monospace fonts.

The fonts live in MCU flash so the firmware does not depend on the font and
icon files that the stock BTT firmware keeps in the TFT's SPI flash.

Source font: DejaVu Sans Mono Bold (Bitstream Vera licence, free to embed).
Usage: python3 tools/gen_fonts.py [path/to/DejaVuSansMono-Bold.ttf]
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

TTF = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf"
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "src", "fonts.c")

ASCII = "".join(chr(c) for c in range(32, 127))
DIGITS = " +-.0123456789XYZ"

# name, pixel size, cell width, cell height, characters
FONTS = [
    ("font_small", 15, 9, 18, ASCII),
    ("font_medium", 21, 13, 26, ASCII),
    ("font_big", 44, 26, 46, DIGITS),
]


def render(size, w, h, chars):
    font = ImageFont.truetype(TTF, size)
    ascent, descent = font.getmetrics()
    top = (h - (ascent + descent)) // 2
    out = bytearray()
    for ch in chars:
        img = Image.new("L", (w, h), 0)
        d = ImageDraw.Draw(img)
        adv = font.getlength(ch)
        d.text(((w - adv) / 2, top), ch, fill=255, font=font)
        px = img.tobytes()
        for i in range(0, len(px), 2):
            a = px[i] >> 4
            b = (px[i + 1] >> 4) if i + 1 < len(px) else 0
            out.append((a << 4) | b)
    return out


def main():
    lines = [
        "// Generated by tools/gen_fonts.py from DejaVu Sans Mono Bold. Do not edit.",
        "// DejaVu fonts: Bitstream Vera licence (free to use and embed).",
        '#include "fonts.h"',
        "",
    ]
    for name, size, w, h, chars in FONTS:
        assert (w * h) % 2 == 0
        data = render(size, w, h, chars)
        lines.append(f"static const uint8_t {name}_data[{len(data)}] = {{")
        for i in range(0, len(data), 24):
            lines.append("  " + ",".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
        lines.append("};")
        esc = chars.replace("\\", "\\\\").replace('"', '\\"')
        lines.append(
            f'const font_t {name} = {{ {w}, {h}, {len(chars)}, "{esc}", {name}_data }};'
        )
        lines.append("")
    with open(OUT, "w") as f:
        f.write("\n".join(lines))
    print("wrote", os.path.normpath(OUT))


if __name__ == "__main__":
    main()
